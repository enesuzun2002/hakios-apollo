#!/usr/bin/env python3
"""
mkmenufont.py: the anti-aliased bitmap fonts of the Mi 10T's boot menu (menu.c), as menu_font.h.

The glyphs are Montserrat's (SIL Open Font License 1.1, xnuloader/fonts/OFL-Montserrat.txt), drawn
by FreeType through Pillow at the sizes the menu uses and kept as 4-bit coverage, ASCII only (and
'\\x7f' for a middle dot). The header is committed; this is needed only to change the fonts.

usage: xnuloader/mkmenufont.py [FONTDIR] > xnuloader/menu_font.h
       FONTDIR: where Montserrat-*.otf are (default /usr/share/fonts/julietaula-montserrat-fonts)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTDIR = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/julietaula-montserrat-fonts'
ASCII = ''.join(chr(c) for c in range(32, 127))
# name, face, pixel size, characters
FONTS = [
    ('menu_font_title', 'Montserrat-SemiBold.otf', 112, 'HakiOS'),
    ('menu_font_body', 'Montserrat-SemiBold.otf', 54, ASCII),
    ('menu_font_small', 'Montserrat-Medium.otf', 38, ASCII + '\x7f'),
    ('menu_font_log', 'Montserrat-Medium.otf', 27, ASCII + '\x7f'),
]


def glyphs(face, size, chars):
    font = ImageFont.truetype(f'{FONTDIR}/{face}', size)
    ascent, descent = font.getmetrics()
    table, data = [], bytearray()
    for code in range(32, 128):
        c = chr(code)
        if c not in chars:
            table.append((0, 0, 0, 0, 0, 0))
            continue
        shape = '·' if code == 0x7f else c
        adv = int(round(font.getlength(shape)))
        l, t, r, b = font.getbbox(shape, anchor='ls')
        w, h = max(r - l, 0), max(b - t, 0)
        nib = []
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), shape, font=font, fill=255, anchor='ls')
            nib = [(v * 15 + 127) // 255 for v in img.tobytes()]
        off = len(data) * 2
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            data.append(nib[i] | nib[i + 1] << 4)
        table.append((w, h, l, t, adv, off))
    return ascent, descent, table, data


def main():
    out = ['/* generated by xnuloader/mkmenufont.py from Montserrat (SIL OFL 1.1, xnuloader/fonts/OFL-Montserrat.txt) */',
           '/* clang-format off */', '']
    for name, face, size, chars in FONTS:
        ascent, descent, table, data = glyphs(face, size, chars)
        out.append(f'static const struct menu_glyph {name}_glyphs[96] = {{')
        for w, h, l, t, adv, off in table:
            out.append(f'\t{{ {w}, {h}, {l}, {t}, {adv}, {off} }},')
        out.append('};')
        out.append(f'static const uint8_t {name}_bits[{max(len(data), 1)}] = {{')
        hexes = [f'0x{b:02x}' for b in data] or ['0']
        for i in range(0, len(hexes), 16):
            out.append('\t' + ', '.join(hexes[i:i + 16]) + ',')
        out.append('};')
        out.append(f'static const struct menu_font {name} = {{ {name}_glyphs, {name}_bits, {ascent}, {descent} }};')
        out.append('')
    print('\n'.join(out))


main()
